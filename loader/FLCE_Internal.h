// ForgedLCE loader core internals.
//
// The core (FLCE_Loader, FLCE_Events, FLCE_Registry, FLCE_DataMods,
// FLCE_Json) never touches game classes directly: it goes through
// FLCE_Backend.h and FLCE_Platform.h, so the same core runs compiled into
// the game or injected into the compiled game as a plugin.
#pragma once

// scripts/apply.ps1 copies include/forgedlce/ForgedLCE.h next to the loader
// files in Minecraft.World, so it is found by a plain include there.
#include "ForgedLCE.h"
#include "FLCE_Strings.h"
#include "FLCE_Platform.h"
#include "FLCE_Backend.h"

#include <string>
#include <vector>
#include <map>

namespace ForgedLCE {

// ---- logging (FLCE_Loader.cpp) ----
void Log(int level, const wchar_t *source, const std::wstring &message);

// Integer to wide string (swprintf/to_wstring differ across platforms).
std::wstring IntToString(int value);

// ---- lifecycle (FLCE_Loader.cpp) ----
// Discovers every mod and runs preInit/init/postInit. Runs once; later calls
// do nothing. Called by the game hook (source builds) or the startup hook
// (injected builds).
void LoadAllMods();

enum LoadPhase {
    PHASE_NOT_STARTED,
    PHASE_CONSTRUCT,
    PHASE_PREINIT,
    PHASE_INIT,
    PHASE_POSTINIT,
    PHASE_DONE
};
LoadPhase CurrentPhase();

// ---- static mods (FLCE_StaticMods.cpp, generated by scripts/apply.ps1) ----
// Mods compiled into the game. On consoles running a source build, this is
// the only kind of code mod.
struct StaticMod {
    const wchar_t  *modId;
    FLCE_ModEntryFn entry;
};
// Terminated by an entry whose modId is NULL.
extern const StaticMod g_staticMods[];

// ---- strings (FLCE_Loader.cpp) ----
// Stores `text` and returns a string id for setDescriptionId().
unsigned int AddModString(const std::wstring &text);
// How many mod strings exist; their ids are STRING_ID_BASE + 0 .. count - 1.
size_t ModStringCount();

// ---- registry (FLCE_Registry.cpp) ----
namespace Registry {
    // Reads the saved name->id map. Call before preInit.
    void LoadIdMap();
    // Writes the name->id map. Call after postInit.
    void SaveIdMap();
    // Rebuilds the console crafting UI cache after recipes were added.
    void FinishRecipes();

    int  RegisterBlock(const FLCE_BlockDesc *desc);
    int  RegisterItem(const FLCE_ItemDesc *desc);
    int  FindId(const wchar_t *registryName);

    int  AddShapedRecipe(int resultId, int resultCount, int resultData,
                         const wchar_t *const *rows, int rowCount,
                         const FLCE_RecipeKey *keys, int keyCount);
    int  AddShapelessRecipe(int resultId, int resultCount, int resultData,
                            const int *ids, int count);
    int  AddSmelting(int inputId, int resultId, int resultCount, int resultData, float xp);

    // Lowest and highest numeric ids handed to mods.
    const int BLOCK_ID_MIN = 1;
    const int BLOCK_ID_MAX = 255;   // chunk storage is one byte per block
    const int ITEM_ID_MIN  = 4096;  // well above vanilla items (max ~2267)
    const int ITEM_ID_MAX  = 31999; // Item::ITEM_NUM_COUNT - 1
}

// ---- events (FLCE_Events.cpp) ----
namespace Events {
    bool Subscribe(int type, FLCE_EventHandler handler, int priority, void *userData);
    // Runs every handler for event->type. Returns event->canceled.
    bool Post(FLCE_Event *event);

    // Called by the game hooks. Do nothing until loading has finished.
    void PostTick(int type, int phase);
    // Return true if a handler canceled the action.
    bool PostBlockBreak(FLCE_Level *level, FLCE_Entity *player, int x, int y, int z, int blockId, int blockData);
    bool PostEntityJoin(FLCE_Level *level, FLCE_Entity *entity, int isPlayer, double x, double y, double z);
}

// ---- data mods (FLCE_DataMods.cpp) ----
// Mods made only of a forgedlce.json file: no code, nothing to compile.
namespace DataMods {
    struct DataMod;
    // Parses <dir>/forgedlce.json. Returns NULL (and logs why) if the file is
    // missing, invalid, or describes a code mod rather than a data mod.
    DataMod *Load(const std::wstring &dir, const std::wstring &folderName);
    const wchar_t *ModId(const DataMod *mod);
    const wchar_t *Name(const DataMod *mod);
    const wchar_t *Version(const DataMod *mod);
    void PreInit(DataMod *mod);   // registers items, then blocks
    void Init(DataMod *mod);      // recipes and smelting
}

// Valid mod ids: non-empty, lowercase a-z, 0-9 and _.
bool IsValidModId(const wchar_t *id);

} // namespace ForgedLCE
